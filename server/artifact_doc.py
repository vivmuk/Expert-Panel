"""Standalone Constellation Paper documents: one shell for every deliverable, and markdown in for catalog artifacts."""
import os
import re
from datetime import date
from functools import lru_cache
from html import escape

STATIC = os.path.join(os.path.dirname(__file__), "static")
DEMO_NOTE = "AI-generated demo engagement from public information. Not commissioned by the company."
LIVE_NOTE = "AI-generated by AI Partner agents from public sources and your answers. Check the cited pages before acting."
FONTS = (
    '<link rel="preconnect" href="https://fonts.googleapis.com"><link rel="preconnect" href="https://fonts.gstatic.com" crossorigin>'
    '<link rel="stylesheet" href="https://fonts.googleapis.com/css2?family=Inter:wght@400..800&family=JetBrains+Mono:wght@400..600'
    '&family=Source+Serif+4:ital,opsz,wght@0,8..60,400..700;1,8..60,400&display=swap">'
)


@lru_cache(maxsize=1)
def _css():
    with open(os.path.join(STATIC, "doc.css"), encoding="utf-8") as handle:
        return handle.read()


def document(title, kicker, body, kind="doc", demo=False):
    today = date.today().strftime("%B %-d, %Y")
    return f"""<!DOCTYPE html>
<html lang="en">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
<title>{escape(title)} · AI Partner</title>
{FONTS}
<style>{_css()}</style>
</head>
<body class="doc {escape(kind)}">
<header class="mast"><span class="brand"><i></i>AI Partner</span><span>{escape(kicker)}</span></header>
<main class="sheet">
{body}
</main>
<footer class="foot"><span>{escape(DEMO_NOTE if demo else LIVE_NOTE)}</span><span>{escape(today)}</span></footer>
</body>
</html>
"""


def as_markdown(title, body, demo=False):
    footer = f"\n\n---\n\n{DEMO_NOTE}\n" if demo else ""
    return f"# {title}\n\n{body.strip()}\n{footer}"


def as_html(title, body, demo=False):
    lines = body.strip().splitlines()
    if lines and lines[0].startswith("# "):
        lines = lines[1:]
    text = "\n".join(lines)
    page = f'<p class="kicker"><b class="red">Catalog artifact</b></p>\n<h1>{escape(title)}</h1>\n<div class="md">{md(text)}</div>'
    return document(title, "Catalog artifact", page, "catalog-doc", demo)


def _inline(text):
    out = escape(text)
    out = re.sub(r"\*\*(.+?)\*\*", r"<b>\1</b>", out)
    out = re.sub(r"(?<![\w*])\*(?!\s)(.+?)(?<!\s)\*(?![\w*])", r"<i>\1</i>", out)
    out = re.sub(r"`([^`]+)`", r"<code>\1</code>", out)
    out = re.sub(r"\[([^\]]+)\]\((https?://[^)\s]+)\)", r'<a href="\2">\1</a>', out)
    return out


def md(body):
    """Headings, paragraphs, lists, tables, quotes, and fenced code. Enough for the catalog artifacts the model writes."""
    parts, para, rows, items, fence = [], [], [], None, None
    list_tag = "ul"

    def flush():
        nonlocal para, rows, items
        if para:
            parts.append(f"<p>{_inline(' '.join(para))}</p>")
            para = []
        if rows:
            parts.append(_table(rows))
            rows = []
        if items is not None:
            parts.append(f"<{list_tag}>" + "".join(f"<li>{_inline(i)}</li>" for i in items) + f"</{list_tag}>")
            items = None

    for line in body.splitlines():
        if fence is not None:
            if line.strip().startswith("```"):
                parts.append(f'<pre class="code">{escape(chr(10).join(fence))}</pre>')
                fence = None
            else:
                fence.append(line)
            continue
        stripped = line.strip()
        if stripped.startswith("```"):
            flush()
            fence = []
            continue
        if stripped.startswith("|"):
            if not rows:
                flush()
            rows.append(stripped)
            continue
        bullet = re.match(r"^\s*(?:[-*+]|(\d+)[.)])\s+(.*)", line)
        if bullet:
            tag = "ol" if bullet.group(1) else "ul"
            if items is None or tag != list_tag:
                flush()
                items, list_tag = [], tag
            items.append(bullet.group(2))
            continue
        heading = re.match(r"^(#{1,4})\s+(.*)", stripped)
        if heading or not stripped or stripped.startswith(">") or stripped in ("---", "***"):
            flush()
        if heading:
            level = min(max(len(heading.group(1)), 2), 4)
            parts.append(f"<h{level}>{_inline(heading.group(2))}</h{level}>")
        elif stripped.startswith(">"):
            parts.append(f"<blockquote>{_inline(stripped.lstrip('> '))}</blockquote>")
        elif stripped in ("---", "***"):
            parts.append("<hr>")
        elif stripped:
            if items is not None:
                flush()
            para.append(stripped)
    if fence is not None:
        parts.append(f'<pre class="code">{escape(chr(10).join(fence))}</pre>')
    flush()
    return "\n".join(parts)


def _table(lines):
    body = []
    for index, line in enumerate(lines):
        cells = [cell.strip() for cell in line.strip().strip("|").split("|")]
        if all(set(cell) <= set("-: ") for cell in cells):
            continue
        tag = "th" if index == 0 else "td"
        body.append("<tr>" + "".join(f"<{tag}>{_inline(cell)}</{tag}>" for cell in cells) + "</tr>")
    return '<div class="table-wrap"><table>' + "".join(body) + "</table></div>"
